package com.napier.sem;

public class Country
{
    /**
     * Countries 3 letter code for example 'XYZ'
     */
    public String code;

    /**
     * Name of country
     */
    public String name;

    /**
     * Continent name
     */
    public String continent;

    /**
     * region name
     */
    public String region;

    /**
     * population number
     */
    public int population;

    /**
     * Capital City
     */
    public String capital;
}